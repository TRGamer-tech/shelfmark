// Turns the texts of the Android app (strings.xml, English and German) into the two
// files src/i18n/app-en.ts and src/i18n/app-de.ts, so the website uses the same words.
//
// Run by hand after the app's texts changed: node scripts/convert-strings.mjs
// The result is committed. The build never runs this and never reads outside web/.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (path) => fileURLToPath(new URL(path, import.meta.url));

function unescape(text) {
  return text
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/\\n/g, "\n")
    .replace(/\\(['"@?])/g, "$1");
}

function convert(xml) {
  const strings = {};
  const plurals = {};
  for (const match of xml.matchAll(/<string name="([^"]+)"[^>]*>([\s\S]*?)<\/string>/g)) strings[match[1]] = unescape(match[2]);
  for (const match of xml.matchAll(/<plurals name="([^"]+)">([\s\S]*?)<\/plurals>/g)) {
    const forms = {};
    for (const item of match[2].matchAll(/<item quantity="([^"]+)">([\s\S]*?)<\/item>/g)) forms[item[1]] = unescape(item[2]);
    plurals[match[1]] = forms;
  }
  return { strings, plurals };
}

function emit(language, { strings, plurals }) {
  const lines = [
    "// Generated by scripts/convert-strings.mjs from the texts of the Android app. Do not edit by hand:",
    "// change the app's strings.xml and run the script again.",
    "",
    "export const strings: Record<string, string> = {",
    ...Object.keys(strings)
      .sort()
      .map((key) => `  ${key}: ${JSON.stringify(strings[key])},`),
    "};",
    "",
    "export const plurals: Record<string, { one: string; other: string }> = {",
    ...Object.keys(plurals)
      .sort()
      .map((key) => `  ${key}: { one: ${JSON.stringify(plurals[key].one ?? plurals[key].other)}, other: ${JSON.stringify(plurals[key].other)} },`),
    "};",
    "",
  ];
  const text = lines.join("\n");
  // Written as escapes so that this file keeps to the rule it checks.
  for (const bad of ["\u00df", "\u2014"]) {
    if (text.includes(bad)) throw new Error(`The ${language} texts contain a character the project does not use: ${JSON.stringify(bad)}`);
  }
  writeFileSync(here(`../src/i18n/app-${language}.ts`), text);
  return Object.keys(strings).length + Object.keys(plurals).length;
}

const english = convert(readFileSync(here("../../app/src/main/res/values/strings.xml"), "utf8"));
const german = convert(readFileSync(here("../../app/src/main/res/values-de/strings.xml"), "utf8"));
// A text that is the same in both languages (the name of the app) is only in the English file.
for (const key of Object.keys(english.strings)) if (!(key in german.strings)) german.strings[key] = english.strings[key];
console.log(`en: ${emit("en", english)} texts, de: ${emit("de", german)} texts`);
